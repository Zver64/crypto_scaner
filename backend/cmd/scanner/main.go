// Command scanner backtests Crypto Scanner strategies from a terminal through
// the backend API, authenticated by an API token. It is pure Go: it reads no
// database and calculates no indicators.
package main

import (
	"context"
	"os"
	"os/signal"
	"syscall"
)

func main() {
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	code := run(ctx, os.Args[1:], os.Stdin, os.Stdout, os.Stderr)
	stop()
	os.Exit(code)
}
