// Command gen writes functions_gen.go from the official TA-Lib function
// metadata (ta_func_api.xml) and the github.com/TA-Lib/ta-lib-cgo wrapper
// signatures. Every generated call is checked against the wrapper source, so a
// metadata and wrapper version mismatch fails generation instead of producing
// wrong argument orders.
package main

import (
	"bytes"
	"encoding/xml"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"go/types"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

const (
	wrapperModule = "github.com/TA-Lib/ta-lib-cgo"
	metadataFile  = "ta_func_api.xml"
	outputFile    = "functions_gen.go"
)

// skippedGroups contain element-wise math on one series, which is meaningless
// for candles and produces non-finite values for ordinary prices (ACOS, LN).
var skippedGroups = map[string]bool{"Math Transform": true}

var skippedFunctions = map[string]bool{
	// These return positions inside the calculation window, so their values
	// change with the amount of loaded history.
	"MAXINDEX": true, "MININDEX": true, "MINMAXINDEX": true,
	// TA-Lib divides by zero without a guard when every candle in the window
	// has open equal to close, which is common for illiquid pairs.
	"IMI": true,
	// TA-Lib divides without a guard, and a zero volume is common; strategy
	// expressions divide safely instead.
	"DIV": true,
	// The second series holds a period for every candle, which no candle
	// field provides.
	"MAVP": true,
}

// optionAliases maps metadata option names to wrapper parameter names where
// they differ, both compared by optionKey. An unknown difference fails
// generation, because same-typed options (fast and slow periods) cannot be
// told apart by type.
var optionAliases = map[string]string{
	"accelerationfactor": "acceleration",
	"afmaximum":          "maximum",
	"afinitlong":         "accelerationinitlong",
	"aflong":             "accelerationlong",
	"afmaxlong":          "accelerationmaxlong",
	"afinitshort":        "accelerationinitshort",
	"afshort":            "accelerationshort",
	"afmaxshort":         "accelerationmaxshort",
	"deviations":         "nbdev",
	"deviationsup":       "nbdevup",
	"deviationsdown":     "nbdevdn",
	"fastma":             "fastmatype",
	"slowma":             "slowmatype",
	"signalma":           "signalmatype",
	"fastdma":            "fastdmatype",
	"slowkma":            "slowkmatype",
	"slowdma":            "slowdmatype",
	"firstperiod":        "timeperiod1",
	"secondperiod":       "timeperiod2",
	"thirdperiod":        "timeperiod3",
	"minimumperiod":      "minperiod",
	"maximumperiod":      "maxperiod",
	"volumefactor":       "vfactor",
}

var inputFields = map[string]string{
	"Open": "open", "High": "high", "Low": "low", "Close": "close", "Volume": "volume",
}

// seriesInput is the metadata type of an arbitrary series. Each such input
// reads the candle field chosen by its own source parameter.
const seriesInput = "Double Array"

var outputStyles = map[string]string{
	"Line":        "indicator.OutputLine",
	"Dashed Line": "indicator.OutputDashedLine",
	"Histogram":   "indicator.OutputHistogram",
	"Upper Limit": "indicator.OutputUpperLimit",
	"Lower Limit": "indicator.OutputLowerLimit",
}

type metadata struct {
	Functions []function `xml:"FinancialFunction"`
}

type function struct {
	Abbreviation string     `xml:"Abbreviation"`
	Description  string     `xml:"ShortDescription"`
	Group        string     `xml:"GroupId"`
	Flags        []string   `xml:"Flags>Flag"`
	Inputs       []argument `xml:"RequiredInputArguments>RequiredInputArgument"`
	Options      []option   `xml:"OptionalInputArguments>OptionalInputArgument"`
	Outputs      []output   `xml:"OutputArguments>OutputArgument"`
}

type argument struct {
	Type string `xml:"Type"`
	Name string `xml:"Name"`
}

type option struct {
	Name         string `xml:"Name"`
	Description  string `xml:"ShortDescription"`
	Type         string `xml:"Type"`
	Minimum      string `xml:"Range>Minimum"`
	Maximum      string `xml:"Range>Maximum"`
	DefaultValue string `xml:"DefaultValue"`
}

type output struct {
	Type  string   `xml:"Type"`
	Name  string   `xml:"Name"`
	Flags []string `xml:"Flags>Flag"`
}

func main() {
	log.SetFlags(0)
	raw, err := os.ReadFile(metadataFile)
	if err != nil {
		log.Fatal(err)
	}
	var functions metadata
	if err := xml.Unmarshal(raw, &functions); err != nil {
		log.Fatalf("parse %s: %v", metadataFile, err)
	}
	signatures, err := wrapperSignatures()
	if err != nil {
		log.Fatal(err)
	}

	var body bytes.Buffer
	body.WriteString("// Code generated by go run ./gen; DO NOT EDIT.\n\npackage talib\n\n")
	body.WriteString("import (\n\t\"crypto-scanner/internal/indicator\"\n\n\tta \"" + wrapperModule + "\"\n)\n\n")
	body.WriteString("var functions = []spec{\n")
	generated := 0
	for _, fn := range functions.Functions {
		if skip(fn) {
			continue
		}
		if err := writeSpec(&body, fn, signatures); err != nil {
			log.Fatalf("%s: %v", fn.Abbreviation, err)
		}
		generated++
	}
	body.WriteString("}\n")

	formatted, err := format.Source(body.Bytes())
	if err != nil {
		log.Fatalf("format generated code: %v", err)
	}
	if err := os.WriteFile(outputFile, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("generated %d of %d TA-Lib functions", generated, len(functions.Functions))
}

func skip(fn function) bool {
	return skippedGroups[fn.Group] || skippedFunctions[fn.Abbreviation]
}

// sourceKeys names the source parameters of the series inputs: "source" for
// one series, "source_0" and "source_1" for two (BETA, CORREL).
func sourceKeys(fn function) []string {
	var keys []string
	for _, input := range fn.Inputs {
		if input.Type == seriesInput {
			keys = append(keys, "source")
		}
	}
	if len(keys) > 1 {
		for index := range keys {
			keys[index] = fmt.Sprintf("source_%d", index)
		}
	}
	return keys
}

type signature struct {
	name       string
	params     []string
	paramNames []string
	results    []string
}

// wrapperSignatures indexes the exported wrapper functions by lower-case name,
// which equals the TA-Lib abbreviation without underscores.
func wrapperSignatures() (map[string]signature, error) {
	listed, err := exec.Command("go", "list", "-m", "-f", "{{.Dir}}", wrapperModule).Output()
	if err != nil {
		return nil, fmt.Errorf("locate %s: %w", wrapperModule, err)
	}
	dir := strings.TrimSpace(string(listed))
	result := map[string]signature{}
	fileSet := token.NewFileSet()
	for _, name := range []string{"functions_gen.go", "lookback_gen.go"} {
		file, err := parser.ParseFile(fileSet, filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		for _, declaration := range file.Decls {
			fn, ok := declaration.(*ast.FuncDecl)
			if !ok || fn.Recv != nil || !fn.Name.IsExported() {
				continue
			}
			params, paramNames := fields(fn.Type.Params)
			results, _ := fields(fn.Type.Results)
			result[strings.ToLower(fn.Name.Name)] = signature{
				name: fn.Name.Name, params: params, paramNames: paramNames, results: results,
			}
		}
	}
	return result, nil
}

// fields returns the type and name of every field; unnamed fields have empty
// names.
func fields(list *ast.FieldList) (fieldTypes, names []string) {
	if list == nil {
		return nil, nil
	}
	for _, field := range list.List {
		if len(field.Names) == 0 {
			fieldTypes = append(fieldTypes, types.ExprString(field.Type))
			names = append(names, "")
		}
		for _, name := range field.Names {
			fieldTypes = append(fieldTypes, types.ExprString(field.Type))
			names = append(names, name.Name)
		}
	}
	return fieldTypes, names
}

func writeSpec(body *bytes.Buffer, fn function, signatures map[string]signature) error {
	key := strings.ToLower(strings.ReplaceAll(fn.Abbreviation, "_", ""))
	call, ok := signatures[key]
	if !ok {
		return fmt.Errorf("wrapper has no function %q", key)
	}
	lookback, ok := signatures[key+"lookback"]
	if !ok {
		return fmt.Errorf("wrapper has no lookback function for %q", key)
	}
	if err := checkSignature(fn, call, lookback); err != nil {
		return fmt.Errorf("wrapper %s does not match metadata: %w", call.name, err)
	}

	indicatorType := strings.ToLower(fn.Abbreviation)
	fmt.Fprintf(body, "{\n\tname: %q,\n\tindicatorType: %q,\n\ttitle: %q,\n\tgroup: %q,\n",
		fn.Abbreviation, indicatorType, fn.Description, fn.Group)
	for _, flag := range fn.Flags {
		switch flag {
		case "Overlap":
			body.WriteString("\toverlap: true,\n")
		case "Candlestick":
			body.WriteString("\tcandlestick: true,\n")
		case "Unstable Period":
			body.WriteString("\tunstable: true,\n")
		default:
			return fmt.Errorf("unknown function flag %q", flag)
		}
	}

	sources := sourceKeys(fn)
	if len(sources) > 2 {
		return fmt.Errorf("%d series inputs are unsupported", len(sources))
	}
	body.WriteString("\tinputs: []string{")
	seen := map[string]bool{}
	series := 0
	for index, input := range fn.Inputs {
		field, ok := inputFields[input.Type]
		if input.Type == seriesInput {
			field, ok = sources[series], true
			series++
		}
		if !ok {
			return fmt.Errorf("unknown input type %q", input.Type)
		}
		if seen[field] {
			return fmt.Errorf("input field %q is used twice", field)
		}
		seen[field] = true
		if index > 0 {
			body.WriteString(", ")
		}
		fmt.Fprintf(body, "%q", field)
	}
	body.WriteString("},\n")

	// Source parameters follow the options, so p indexes the options in
	// lookback and call.
	if len(fn.Options) > 0 || len(sources) > 0 {
		body.WriteString("\tparams: []param{\n")
		for _, option := range fn.Options {
			if err := writeParam(body, option); err != nil {
				return err
			}
		}
		for index, key := range sources {
			title := "Source"
			if len(sources) > 1 {
				title = []string{"First Source", "Second Source"}[index]
			}
			fmt.Fprintf(body, "\t\t{key: %q, title: %q, description: %q, kind: paramSource, defaultValue: sourceClose},\n",
				key, title, "Candle field the series is read from")
		}
		body.WriteString("\t},\n")
	}

	body.WriteString("\toutputs: []output{\n")
	for _, out := range fn.Outputs {
		if len(out.Flags) != 1 || outputStyles[out.Flags[0]] == "" {
			return fmt.Errorf("output %q has unsupported flags %v", out.Name, out.Flags)
		}
		name := indicatorType
		if len(fn.Outputs) > 1 {
			name = outputName(out.Name)
		}
		fmt.Fprintf(body, "\t\t{name: %q, style: %s},\n", name, outputStyles[out.Flags[0]])
	}
	body.WriteString("\t},\n")

	arguments := make([]string, len(fn.Options))
	for index, option := range fn.Options {
		if option.Type == "Double" {
			arguments[index] = fmt.Sprintf("p[%d]", index)
		} else {
			arguments[index] = fmt.Sprintf("int(p[%d])", index)
		}
	}
	fmt.Fprintf(body, "\tlookback: func(p []float64) int { return ta.%s(%s) },\n", lookback.name, strings.Join(arguments, ", "))

	callArguments := make([]string, 0, len(call.params))
	for index := range fn.Inputs {
		callArguments = append(callArguments, fmt.Sprintf("in[%d]", index))
	}
	callArguments = append(callArguments, arguments...)
	outputs := make([]string, len(fn.Outputs))
	converted := make([]string, len(fn.Outputs))
	for index, out := range fn.Outputs {
		callArguments = append(callArguments, "nil")
		outputs[index] = fmt.Sprintf("o%d", index)
		converted[index] = outputs[index]
		if out.Type == "Integer Array" {
			converted[index] = fmt.Sprintf("integers(o%d)", index)
		}
	}
	fmt.Fprintf(body, "\tcall: func(in [][]float64, p []float64) [][]float64 {\n\t\t%s := ta.%s(%s)\n\t\treturn [][]float64{%s}\n\t},\n",
		strings.Join(outputs, ", "), call.name, strings.Join(callArguments, ", "), strings.Join(converted, ", "))
	body.WriteString("},\n")
	return nil
}

func checkSignature(fn function, call, lookback signature) error {
	want := make([]string, 0, len(fn.Inputs)+len(fn.Options)+len(fn.Outputs))
	for range fn.Inputs {
		want = append(want, "[]float64")
	}
	var options []string
	for _, option := range fn.Options {
		switch option.Type {
		case "Integer", "MA Type":
			options = append(options, "int")
		case "Double":
			options = append(options, "float64")
		default:
			return fmt.Errorf("unknown option type %q", option.Type)
		}
	}
	want = append(want, options...)
	var results []string
	for _, out := range fn.Outputs {
		switch out.Type {
		case "Double Array":
			results = append(results, "[]float64")
		case "Integer Array":
			results = append(results, "[]int32")
		default:
			return fmt.Errorf("unknown output type %q", out.Type)
		}
	}
	want = append(want, results...)
	if !slices.Equal(call.params, want) || !slices.Equal(call.results, results) {
		return fmt.Errorf("signature (%v) %v, metadata expects (%v) %v", call.params, call.results, want, results)
	}
	if !slices.Equal(lookback.params, options) || !slices.Equal(lookback.results, []string{"int"}) {
		return fmt.Errorf("lookback signature (%v) %v, metadata expects (%v) int", lookback.params, lookback.results, options)
	}
	for index, option := range fn.Options {
		want := optionKey(option.Name)
		if alias, ok := optionAliases[want]; ok {
			want = alias
		}
		for _, names := range [][]string{call.paramNames[len(fn.Inputs):], lookback.paramNames} {
			if got := optionKey(names[index]); got != want {
				return fmt.Errorf("option %d is %q in metadata but %q in the wrapper", index, option.Name, names[index])
			}
		}
	}
	return nil
}

// optionKey compares option names ignoring case and punctuation, so
// "Fast-K Period" matches fastK_Period.
func optionKey(name string) string {
	return nonAlphanumeric.ReplaceAllString(strings.ToLower(name), "")
}

var nonAlphanumeric = regexp.MustCompile(`[^a-z0-9]+`)

func writeParam(body *bytes.Buffer, option option) error {
	key := strings.Trim(nonAlphanumeric.ReplaceAllString(strings.ToLower(option.Name), "_"), "_")
	if option.Name == "Time Period" {
		key = "period"
	}
	defaultValue, err := strconv.ParseFloat(option.DefaultValue, 64)
	if err != nil {
		return fmt.Errorf("option %q default: %w", option.Name, err)
	}
	fmt.Fprintf(body, "\t\t{key: %q, title: %q, description: %q, ", key, option.Name, option.Description)
	if option.Type == "MA Type" {
		fmt.Fprintf(body, "kind: paramMAType, defaultValue: %s},\n", number(defaultValue))
		return nil
	}
	minimum, err := strconv.ParseFloat(option.Minimum, 64)
	if err != nil {
		return fmt.Errorf("option %q minimum: %w", option.Name, err)
	}
	maximum, err := strconv.ParseFloat(option.Maximum, 64)
	if err != nil {
		return fmt.Errorf("option %q maximum: %w", option.Name, err)
	}
	kind := "paramInteger"
	if option.Type == "Double" {
		kind = "paramReal"
	}
	fmt.Fprintf(body, "kind: %s, minimum: %s, maximum: %s, defaultValue: %s},\n",
		kind, number(minimum), number(maximum), number(defaultValue))
	return nil
}

func number(value float64) string { return strconv.FormatFloat(value, 'g', -1, 64) }

// outputName turns outMACDSignal into macdsignal and outRealUpperBand into
// upperband.
func outputName(name string) string {
	name = strings.TrimPrefix(name, "out")
	if trimmed := strings.TrimPrefix(name, "Real"); trimmed != "" {
		name = trimmed
	}
	return strings.ToLower(name)
}
